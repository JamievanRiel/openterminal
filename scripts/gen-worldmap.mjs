#!/usr/bin/env node
/**
 * One-off generator for src/renderer/src/assets/worldLand.ts — a compact SVG
 * path of world land masses (equirectangular projection, 1000×500 viewBox)
 * from Natural Earth 110m data. The output is committed; re-run only to
 * refresh the source data:  node scripts/gen-worldmap.mjs
 */
import { writeFileSync } from 'fs'

const SRC = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson'
const W = 1000
const H = 500

const px = (lon) => Math.round(((lon + 180) / 360) * W * 10) / 10
const py = (lat) => Math.round(((90 - lat) / 180) * H * 10) / 10

const res = await fetch(SRC)
if (!res.ok) throw new Error(`HTTP ${res.status} fetching ${SRC}`)
const geo = await res.json()

let path = ''
let rings = 0
for (const feature of geo.features) {
  const polys = feature.geometry.type === 'Polygon' ? [feature.geometry.coordinates] : feature.geometry.coordinates
  for (const poly of polys) {
    for (const ring of poly) {
      if (ring.length < 8) continue // skip specks that add bytes, not shape
      rings++
      let prev = null
      const parts = []
      for (const [lon, lat] of ring) {
        const x = px(lon)
        const y = py(lat)
        if (prev && prev[0] === x && prev[1] === y) continue // rounding dupes
        parts.push(`${x} ${y}`)
        prev = [x, y]
      }
      path += `M${parts.join('L')}Z`
    }
  }
}

const out = `// GENERATED by scripts/gen-worldmap.mjs from Natural Earth 110m land data
// (public domain). Equirectangular projection into a ${W}×${H} viewBox.
export const WORLD_W = ${W}
export const WORLD_H = ${H}
export const WORLD_LAND_PATH =
  '${path}'
`
writeFileSync(new URL('../src/renderer/src/assets/worldLand.ts', import.meta.url), out)
console.log(`wrote worldLand.ts: ${rings} rings, ${(out.length / 1024).toFixed(1)} KB`)
